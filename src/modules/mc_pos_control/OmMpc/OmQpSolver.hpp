#pragma once
#include <cstdint>
#ifndef OM_MPC_MAX_HORIZON
#define OM_MPC_MAX_HORIZON 20
#endif
inline constexpr int OmMaxHorizon = OM_MPC_MAX_HORIZON;
inline constexpr unsigned om_arena_capacity(int horizon)
{
	// nx=9, nu=4 float32, with headroom for both 32- and 64-bit pointers.
	// N15 uses 75232 bytes on v5 and 78832 bytes on the SITL host.
	return horizon <= 10 ? 65536u : horizon <= 15 ? 81920u : 106496u;
}
// Fixed-size, row-major, Eigen-free interchange for the OM-MPC error-state OCP.
struct OmFloatProblem {
	int32_t horizon;
	float dt;
	float x0[9], q[9], p[9], r[4], reference_input[4];
	float a[OmMaxHorizon][81], b[OmMaxHorizon][36], c[OmMaxHorizon][9], lower[OmMaxHorizon][4], upper[OmMaxHorizon][4];
};

static_assert(sizeof(OmFloatProblem) == 148 + 536 * OmMaxHorizon, "float problem layout");
struct OmFloatResult {
	int status, iterations;
	bool finite;
	bool resumable; // finite iteration-limit state; never authorizes control output
	bool recovery_attempted, recovery_succeeded;
	float primal_residual;
	uint32_t arena_used;
	float inputs[4]; // Only the first control is applied; all stages are checked internally.
};

static_assert(sizeof(OmFloatResult) <= 40, "Only the first control belongs in the result");
// Exclusive to the OmMpc worker. No allocation during warm updates.
// Consecutive converged solves use a predicted dual guess; all constraints
// and convergence checks are still evaluated by qpDUNES.
// Use only for the invariant zero blocks generated by OmMpcModel. Arbitrary
// dense replay uses the generic path; numerical/constraint checks are unchanged.
enum class OmQpLayout { Generic, OmErrorState };
// qpDUNES stops on the L2 norm of all 9*N continuity residuals, not on a
// single component. Float32 roundoff can keep this norm above 1e-6 even at
// the optimum. The independent per-component primal check remains 2e-5.
inline constexpr float OmQpTolerance = 1e-5f;
bool om_float_update(const OmFloatProblem &, float tolerance = OmQpTolerance, OmQpLayout layout = OmQpLayout::Generic);
OmFloatResult om_float_solve(const OmFloatProblem &, int iteration_limit = 100);
void om_float_close();
